const fs = require('node:fs');
const path = require('node:path');
const parts = ['model.js','index.js','board.js','plugin.js'];
const header = "// Generated by node dashboard/build.cjs. Edit src/, then rebuild.\n'use strict';\nconst {Plugin, ItemView, MarkdownRenderChild, PluginSettingTab, Setting, Notice, moment, setIcon} = require('obsidian');\n";
// User-supplied cat.jpg, embedded unchanged so installs still need only three files.
const avatar=fs.readFileSync(path.join(__dirname,'assets','cat.jpg')).toString('base64');
const output = header + `const AVATAR_SRC = 'data:image/jpeg;base64,${avatar}';\n` + parts.map(name => `\n// ${name}\n${fs.readFileSync(path.join(__dirname,'src',name),'utf8')}`).join('\n');
fs.writeFileSync(path.join(__dirname,'main.js'),output);
console.log('Built dashboard/main.js');
